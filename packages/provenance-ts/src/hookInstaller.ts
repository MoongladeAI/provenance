import * as fs from 'fs/promises';
import * as path from 'path';
import * as readline from 'readline';
import { execFile } from 'child_process';

export interface HookSelection {
  preCommit: boolean;
  mcpVerifyRead: boolean;
  mcpAutoSeal: boolean;
}

export interface InstallOptions extends HookSelection {
  cwd?: string;
  /** Replace a hook that was not installed by this tool, after backing it up. */
  force?: boolean;
}

export interface HookResult {
  path: string;
  action: 'created' | 'unchanged' | 'updated' | 'replaced';
  backup?: string;
}

export interface InstallResult {
  /** What the manifest now records (selected options merged with earlier recorded state). */
  selection: HookSelection;
  hooksDir: string | null;
  hook: HookResult | null;
  manifestPath: string;
  manifestBackup?: string;
}

/** Marker line (line 2 of the generated hook). A hook is ours only if its whole content equals a known generated version. */
export const HOOK_MARKER = '# moonglade-provenance-hook v1';

export class HookConflictError extends Error {
  constructor(public readonly hookPath: string) {
    super(`${hookPath} already exists and is not an unmodified hook generated by Moonglade Provenance (it may be foreign or edited). It was left unchanged. Re-run with --force to back it up and replace it.`);
    this.name = 'HookConflictError';
  }
}

function git(cwd: string, args: string[]): Promise<{ ok: boolean; missing: boolean; out: string }> {
  return new Promise(resolve => {
    execFile('git', args, { cwd, windowsHide: true }, (err, stdout) => {
      if (err) resolve({ ok: false, missing: (err as NodeJS.ErrnoException).code === 'ENOENT', out: '' });
      else resolve({ ok: true, missing: false, out: String(stdout).trim() });
    });
  });
}

export async function findGitRoot(startDir: string = process.cwd()): Promise<string | null> {
  let curr = path.resolve(startDir);
  while (true) {
    try {
      const stat = await fs.stat(path.join(curr, '.git'));
      if (stat.isDirectory()) return curr;
    } catch {
      // not in this dir
    }
    const parent = path.dirname(curr);
    if (parent === curr) return null;
    curr = parent;
  }
}

/**
 * Hooks directory as git itself resolves it (`git rev-parse --git-path hooks`), so linked worktrees,
 * submodules and core.hooksPath work. Falls back to a `.git` directory only when git is not installed.
 * Returns null when cwd is not inside a repository.
 */
export async function resolveHooksDir(cwd: string = process.cwd()): Promise<string | null> {
  const r = await git(cwd, ['rev-parse', '--git-path', 'hooks']);
  if (r.ok) return path.resolve(cwd, r.out);
  if (r.missing) {
    const root = await findGitRoot(cwd);
    return root ? path.join(root, '.git', 'hooks') : null;
  }
  return null;
}

async function resolveTopLevel(cwd: string): Promise<string> {
  const r = await git(cwd, ['rev-parse', '--show-toplevel']);
  return r.ok ? path.resolve(cwd, r.out) : path.resolve(cwd);
}

/**
 * The generated pre-commit hook. Written for bash (not POSIX sh): it reads NUL-delimited names (`read -d ''`)
 * so file names with spaces, non-ASCII characters (git would quote them otherwise) or newlines are all checked.
 * Fail closed: if the staged list cannot be read, the commit is blocked.
 */
export const PRE_COMMIT_SCRIPT = `#!/usr/bin/env bash
${HOOK_MARKER}
# Moonglade Provenance - Git Pre-Commit Verification Gate (requires bash)
# Blocks the commit when a staged artifact that has a provenance sidecar no longer matches it.

echo "Moonglade Provenance: Verifying staged artifacts..."

TMP_LIST=$(mktemp) || exit 1
trap 'rm -f "$TMP_LIST"' EXIT
if ! git diff --cached --name-only -z --diff-filter=ACMR > "$TMP_LIST"; then
  echo "Moonglade Provenance: could not list staged files; commit aborted."
  exit 1
fi

FAILED=0
while IFS= read -r -d '' FILE; do
  case "$FILE" in
    *.provenance.json|*.provenance-registry.json) continue ;;
    *.md|*.csv|*.json|*.sql|*.yml|*.yaml) ;;
    *) continue ;;
  esac
  [ -f "$FILE" ] || continue
  [ -f "$FILE.provenance.json" ] || continue
  TARGET="$FILE"
  case "$TARGET" in -*) TARGET="./$TARGET" ;; esac
  if ! npx --no-install @moonglade/provenance badge "$TARGET" --short < /dev/null > /dev/null 2>&1; then
    echo "[PROVENANCE DRIFT] $FILE has mutated or failed verification!"
    FAILED=1
  fi
done < "$TMP_LIST"

if [ "$FAILED" -ne 0 ]; then
  echo ""
  echo "Commit aborted by Moonglade Provenance Gate."
  echo "Please re-seal mutated artifacts before committing:"
  echo "  npx @moonglade/provenance seal-provisional <file>"
  echo ""
  exit 1
fi

echo "All staged artifacts verified."
exit 0
`;

/** Generated hook contents this tool has shipped. A hook is ours only if its content equals one of these exactly. */
const KNOWN_GENERATED_HOOKS: string[] = [PRE_COMMIT_SCRIPT];

function backupStamp(): string {
  return new Date().toISOString().replace(/\.\d+Z$/, 'Z').replace(/[-:]/g, '');
}

/** Copy a file to `<file>.bak-<UTC timestamp>` (exclusive create, counter suffix on collision). */
async function backupFile(file: string): Promise<string> {
  const stamp = backupStamp();
  for (let i = 0; ; i++) {
    const candidate = `${file}.bak-${stamp}${i ? '-' + i : ''}`;
    try {
      await fs.copyFile(file, candidate, 1 /* COPYFILE_EXCL */);
      return candidate;
    } catch (e) {
      if ((e as NodeJS.ErrnoException).code !== 'EEXIST') throw e;
    }
  }
}

/**
 * Install one hook script. An existing hook is replaced only if its content equals a known generated version
 * (`known`, default: the shipped hook). Anything else, including our own hook with an edit or a foreign hook
 * that merely mentions the marker, is refused unless `force`, and a forced replace is backed up first.
 */
export async function installGitHook(hooksDir: string, hookName: string, scriptContent: string, opts: { force?: boolean; known?: string[] } = {}): Promise<HookResult> {
  await fs.mkdir(hooksDir, { recursive: true });
  const hookPath = path.join(hooksDir, hookName);
  const known = opts.known ?? KNOWN_GENERATED_HOOKS;
  let existing: string | null = null;
  try {
    existing = await fs.readFile(hookPath, 'utf8');
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code !== 'ENOENT') throw e;
  }
  let action: HookResult['action'] = 'created';
  let backup: string | undefined;
  if (existing !== null) {
    if (existing === scriptContent) {
      action = 'unchanged';
    } else if (known.includes(existing)) {
      action = 'updated';
    } else {
      if (!opts.force) throw new HookConflictError(hookPath);
      action = 'replaced';
      backup = await backupFile(hookPath);
    }
  }
  if (action !== 'unchanged') {
    await fs.writeFile(hookPath, scriptContent, { mode: 0o755 });
  }
  await fs.chmod(hookPath, 0o755);
  return backup ? { path: hookPath, action, backup } : { path: hookPath, action };
}

function manifestPayload(selection: HookSelection): Record<string, unknown> {
  const payload: Record<string, unknown> = {
    standard: MANIFEST_STANDARD,
    hooks: selection
  };
  if (selection.mcpVerifyRead || selection.mcpAutoSeal) {
    payload.mcpServer = { command: 'npx', args: ['-y', '@moonglade/provenance', 'provenance-gate'] };
  }
  return payload;
}

/** Previously recorded choices from an existing manifest, or null when absent or unreadable. */
async function readRecordedHooks(file: string): Promise<{ parsed: Record<string, unknown> | null; raw: string | null }> {
  let raw: string;
  try {
    raw = await fs.readFile(file, 'utf8');
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code === 'ENOENT') return { parsed: null, raw: null };
    throw e;
  }
  try {
    const parsed = JSON.parse(raw);
    return { parsed: parsed && typeof parsed === 'object' ? parsed : null, raw };
  } catch {
    return { parsed: null, raw };
  }
}

const MANIFEST_STANDARD = 'Moonglade Provenance Hook Manifest v1';

/** True only for a manifest of exactly the shape this tool writes. Anything else (user keys, other standard, bad JSON) is backed up before a rewrite. */
function isOurManifest(parsed: Record<string, unknown> | null): boolean {
  if (!parsed || parsed.standard !== MANIFEST_STANDARD) return false;
  const allowed = new Set(['standard', 'installedAt', 'hooks', 'mcpServer']);
  if (!Object.keys(parsed).every(k => allowed.has(k))) return false;
  const hooks = parsed.hooks as Record<string, unknown> | undefined;
  if (!hooks || typeof hooks !== 'object') return false;
  const hk = new Set(['preCommit', 'mcpVerifyRead', 'mcpAutoSeal']);
  return Object.keys(hooks).every(k => hk.has(k) && typeof hooks[k] === 'boolean');
}

/**
 * Write the manifest. An existing manifest that is not exactly in the shape this tool writes is backed up first.
 */
export async function writeProvenanceConfig(dir: string, selection: HookSelection): Promise<{ path: string; backup?: string }> {
  const configPath = path.join(dir, '.provenance-hooks.json');
  const payload = manifestPayload(selection);
  const { parsed, raw } = await readRecordedHooks(configPath);
  let backup: string | undefined;
  if (raw !== null && !isOurManifest(parsed)) backup = await backupFile(configPath);
  const out = { standard: payload.standard, installedAt: new Date().toISOString(), ...payload };
  await fs.writeFile(configPath, JSON.stringify(out, null, 2) + '\n', 'utf8');
  return backup ? { path: configPath, backup } : { path: configPath };
}

/**
 * Install exactly the selected gates. Nothing is enabled that was not selected. The manifest records the
 * selected options merged with earlier recorded MCP choices (never switched off silently) and with reality:
 * preCommit is true when an unmodified generated pre-commit hook is installed.
 */
export async function installHooks(opts: InstallOptions): Promise<InstallResult> {
  const cwd = path.resolve(opts.cwd ?? process.cwd());
  const selected: HookSelection = {
    preCommit: opts.preCommit === true,
    mcpVerifyRead: opts.mcpVerifyRead === true,
    mcpAutoSeal: opts.mcpAutoSeal === true
  };
  let hooksDir: string | null = null;
  let hook: HookResult | null = null;
  if (selected.preCommit) {
    hooksDir = await resolveHooksDir(cwd);
    if (!hooksDir) throw new Error(`pre-commit hook requested but ${cwd} is not inside a git repository`);
    hook = await installGitHook(hooksDir, 'pre-commit', PRE_COMMIT_SCRIPT, { force: opts.force });
  } else {
    hooksDir = await resolveHooksDir(cwd);
  }
  const top = await resolveTopLevel(cwd);
  const recorded = (await readRecordedHooks(path.join(top, '.provenance-hooks.json'))).parsed?.hooks as Partial<HookSelection> | undefined;
  let installed = false;
  if (hooksDir) {
    try {
      installed = KNOWN_GENERATED_HOOKS.includes(await fs.readFile(path.join(hooksDir, 'pre-commit'), 'utf8'));
    } catch { /* no hook */ }
  }
  const selection: HookSelection = {
    preCommit: selected.preCommit || installed,
    mcpVerifyRead: selected.mcpVerifyRead || recorded?.mcpVerifyRead === true,
    mcpAutoSeal: selected.mcpAutoSeal || recorded?.mcpAutoSeal === true
  };
  const manifest = await writeProvenanceConfig(top, selection);
  return { selection, hooksDir, hook, manifestPath: manifest.path, manifestBackup: manifest.backup };
}

export const HOOK_FLAGS = ['--pre-commit', '--mcp-verify-read', '--mcp-auto-seal', '--force'] as const;

export const HOOK_USAGE = 'usage: provenance install-hooks [--pre-commit] [--mcp-verify-read] [--mcp-auto-seal] [--force]\n' +
  '  --pre-commit        install the git pre-commit verification gate\n' +
  '  --mcp-verify-read   record the fail-closed verify-on-read MCP option\n' +
  '  --mcp-auto-seal     record the provisional auto-seal-on-agent-write MCP option\n' +
  '  --force             replace an existing hook that is not ours, after backing it up to <hook>.bak-<UTC timestamp>\n' +
  'With no choice flag, the command asks about each option when run in a terminal and does nothing otherwise.';

/** CLI entry. Returns the process exit code. */
export async function runInstallHooksCli(args: string[], cwd: string = process.cwd()): Promise<number> {
  const unknown = args.filter(a => !(HOOK_FLAGS as readonly string[]).includes(a));
  if (unknown.length) {
    console.error(`unknown argument: ${unknown.join(' ')}\n${HOOK_USAGE}`);
    return 2;
  }
  const has = (f: string) => args.includes(f);
  let selection: HookSelection = { preCommit: has('--pre-commit'), mcpVerifyRead: has('--mcp-verify-read'), mcpAutoSeal: has('--mcp-auto-seal') };
  if (!selection.preCommit && !selection.mcpVerifyRead && !selection.mcpAutoSeal) {
    if (!process.stdin.isTTY || !process.stdout.isTTY) {
      console.error(`no option selected and no terminal to ask.\n${HOOK_USAGE}`);
      return 2;
    }
    selection = await askInteractively();
  }
  try {
    const r = await installHooks({ cwd, ...selection, force: has('--force') });
    if (r.hook) {
      console.log(`${r.hook.action}: ${r.hook.path}`);
      if (r.hook.backup) console.log(`backup of previous hook: ${r.hook.backup}`);
    }
    console.log(`manifest: ${r.manifestPath}`);
    if (r.manifestBackup) console.log(`backup of previous manifest: ${r.manifestBackup}`);
    console.log(`enabled: ${JSON.stringify(r.selection)}`);
    if (selection.mcpVerifyRead || selection.mcpAutoSeal) {
      console.log('MCP configuration snippet:');
      console.log(JSON.stringify({ mcpServers: { 'provenance-gate': { command: 'npx', args: ['-y', '@moonglade/provenance', 'provenance-gate'] } } }, null, 2));
    }
    return 0;
  } catch (e) {
    console.error((e as Error).message);
    return 1;
  }
}

async function askInteractively(): Promise<HookSelection> {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  const ask = (q: string, def: boolean): Promise<boolean> =>
    new Promise(resolve => rl.question(`${q} (${def ? 'Y/n' : 'y/N'}): `, a => {
      const t = a.trim().toLowerCase();
      resolve(t === '' ? def : t === 'y' || t === 'yes');
    }));
  try {
    return {
      preCommit: await ask('Install the git pre-commit verification gate?', true),
      mcpVerifyRead: await ask('Record the fail-closed verify-on-read MCP option?', false),
      mcpAutoSeal: await ask('Record the provisional auto-seal-on-agent-write MCP option?', false)
    };
  } finally {
    rl.close();
  }
}
